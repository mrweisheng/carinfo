    def _update_list_only(self, records):
        """兜底行专用更新：只写列表页可靠的字段。

        为什么单独一条 SQL，不复用 `_update_via_database`：
        兜底行的 description / contact_info / contact_name / phone_number / extra_fields
        都是**空值占位**（car28._build_fallback_car 只填列表页字段）。走全字段 UPDATE 会把
        这辆老车此前攒下的详情数据整行抹掉，而它一旦掉出抓取范围就再也补不回来。
        这里只更新「列表页确实有、且详情页不产出」的字段，详情字段原样保留。

        记录元组顺序：(vehicle_status, page_number, car_url, price,
                      current_price, original_price, vehicle_id)
        """
        sql = """
        UPDATE vehicles SET
            vehicle_status = %s, page_number = %s, car_url = %s,
            price = %s, current_price = %s, original_price = %s,
            updated_at = CURRENT_TIMESTAMP
        WHERE vehicle_id = %s
        """
        execute_batch(self.cursor, sql, records, page_size=100)
        self.connection.commit()

    def _update_via_database(self, batch_vehicles):
        """数据库更新方案 - 更新所有字段"""
        try:
            update_sql = """
            UPDATE vehicles SET
                vehicle_type = %s, vehicle_status = %s, page_number = %s,
                car_number = %s, car_url = %s, car_category = %s, car_brand = %s, car_model = %s,
                fuel_type = %s, seats = %s, engine_volume = %s, transmission = %s, year = %s,
                description = %s, price = %s, current_price = %s, original_price = %s,
                contact_info = %s, update_date = %s, extra_fields = %s,
                contact_name = %s, phone_number = %s,
                updated_at = CURRENT_TIMESTAMP
            WHERE vehicle_id = %s
            """

            update_data = []
            for vehicle_data in batch_vehicles:
                # 字段顺序（与 vehicle_data 元组下标对应，勿随意调整）:
                # vehicle_type, vehicle_status, page_number, car_number, car_url,
                # car_category, car_brand, car_model, fuel_type, seats, engine_volume,
                # transmission, year, description, price, current_price, original_price,
                # contact_info, update_date, extra_fields, contact_name, phone_number, vehicle_id
                record = (
                    vehicle_data[1],   # vehicle_type
                    vehicle_data[2],   # vehicle_status
                    vehicle_data[3],   # page_number
                    vehicle_data[4],   # car_number
                    vehicle_data[5],   # car_url
                    vehicle_data[6],   # car_category
                    vehicle_data[7],   # car_brand
                    vehicle_data[8],   # car_model
                    vehicle_data[9],   # fuel_type
                    vehicle_data[10],  # seats
                    vehicle_data[11],  # engine_volume
                    vehicle_data[12],  # transmission
                    vehicle_data[13],  # year
                    vehicle_data[14],  # description
                    vehicle_data[15],  # price
                    vehicle_data[16],  # current_price
                    vehicle_data[17],  # original_price
                    vehicle_data[18],  # contact_info
                    vehicle_data[19],  # update_date
                    vehicle_data[20],  # extra_fields
                    vehicle_data[21],  # contact_name
                    vehicle_data[22],  # phone_number
                    vehicle_data[0]     # vehicle_id (WHERE条件)
                )
                update_data.append(record)

            execute_batch(self.cursor, update_sql, update_data, page_size=100)
            self.connection.commit()

        except Exception as e:
            print(f"数据库更新失败: {e}")
            if self.connection:
                self.connection.rollback()
            # 必须向上抛：调用方靠异常把该批次计入 error_update_count，
            # 吞掉异常会让失败批次被记成成功，爬取日志统计失真
            raise
    
    def close(self):
        """关闭连接"""
        if self.cursor:
            self.cursor.close()
        if self.connection:
            self.connection.close()
        print("[OK] 数据库连接已关闭")

